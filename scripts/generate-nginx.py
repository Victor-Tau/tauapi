#!/usr/bin/env python3
"""Generate the Nginx site for api.victor-tau.xyz from ROUTE_CONTRACT.json.

Usage:
  generate-nginx.py --contract ROUTE_CONTRACT.json --mode maintenance|live \
      --upstreams 127.0.0.1:3001,127.0.0.1:3002 [--out FILE] [--check-plugins DIR]

Modes:
  maintenance  public clients get 503 except ACME; loopback clients (real
               connection source 127.0.0.1/::1, not headers) get the full site
               so the site can be verified over HTTPS before opening.
  live         full site for everyone.

The upstream list is written to a separate include file
(/etc/nginx/tauapi/upstream-backend.conf) by deploy-backend.sh, so a backend
rolling release never regenerates this file.

Exit codes: 0 ok, 2 usage, 5 route conflict.
"""
import argparse
import json
import os
import re
import sys

DOMAIN = "api.victor-tau.xyz"
CERT_DIR = f"/etc/letsencrypt/live/{DOMAIN}"


def page_location_regex(contract):
    pages = contract["frontend_pages"]
    exact = sorted({p for p in pages["exact"] if p != "/"})
    prefix = sorted(set(pages["prefix"]))
    exact_alt = "|".join(re.escape(p.lstrip("/")) for p in exact)
    prefix_alt = "|".join(re.escape(p.lstrip("/")) for p in prefix)
    # exact pages (with optional trailing slash) or page prefixes followed by
    # end, slash or nothing else.
    return f"^/(?:(?:{exact_alt})/?|(?:{prefix_alt})(?:/.*)?)$"


def check_plugin_conflicts(contract, plugin_dir):
    """Fail if a plugin route lands under a reserved namespace or SPA page."""
    reserved = contract["reserved_namespaces"]
    pages = contract["frontend_pages"]
    page_prefixes = [p.rstrip("/") for p in pages["prefix"]]
    exceptions = ["/dashboard/billing/"]
    conflicts = []
    for root, _, files in os.walk(plugin_dir):
        for f in files:
            if not f.endswith((".js", ".mjs", ".ts")):
                continue
            text = open(os.path.join(root, f), encoding="utf-8", errors="replace").read()
            for m in re.finditer(r"path:\s*['\"](/[^'\"]*)['\"]", text):
                path = m.group(1)
                if any(path.startswith(r) for r in reserved):
                    conflicts.append((f, path, "reserved namespace"))
                if path in pages["exact"] and path != "/":
                    conflicts.append((f, path, "frontend page"))
                for pp in page_prefixes:
                    if (path == pp or path.startswith(pp + "/")) and not any(path.startswith(e) for e in exceptions):
                        conflicts.append((f, path, f"frontend prefix {pp}"))
    return conflicts


def render(contract, mode):
    page_re = page_location_regex(contract)
    root_files = contract["frontend_assets"]["root_public_files"]
    root_files_re = "^/(?:" + "|".join(re.escape(f.lstrip("/")) for f in root_files) + ")$"
    gate = ""
    if mode == "maintenance":
        gate = """
    # Maintenance gate: only the real loopback connection source may use the
    # full site (local HTTPS acceptance); public clients get 503.
    if ($tauapi_gate_block) { return 503; }
"""
    return f"""# Generated by ops/scripts/generate-nginx.py from ROUTE_CONTRACT.json (mode={mode}).
# Do not edit by hand; regenerate and run `nginx -t` before reload.

map $http_upgrade $connection_upgrade {{
    default upgrade;
    ''      close;
}}

# Real connection source, never a forwarded header.
geo $remote_addr $tauapi_public_client {{
    default 1;
    127.0.0.1/32 0;
    ::1/128 0;
}}

# Re-evaluated after internal redirects so the maintenance page itself is served.
map "$tauapi_public_client:$uri" $tauapi_gate_block {{
    volatile;
    default 0;
    "~^1:/(?!__maintenance\\.html$)" 1;
}}

log_format tauapi_safe '$remote_addr - [$time_local] "$request_method $uri $server_protocol" '
                       '$status $body_bytes_sent $request_time "$http_user_agent" up=$upstream_addr';

include /etc/nginx/tauapi/upstream-backend.conf;

server {{
    listen 80;
    listen [::]:80;
    server_name {DOMAIN};
    access_log /var/log/nginx/tauapi.access.log tauapi_safe;

    location ^~ /.well-known/acme-challenge/ {{
        root /var/www/tauapi-acme;
        default_type text/plain;
        try_files $uri =404;
    }}
    location / {{
        return 301 https://$host$request_uri;
    }}
}}

server {{
    # nginx 1.24 (Ubuntu 24.04): http2 is a listen parameter.
    listen 443 ssl http2;
    listen [::]:443 ssl http2;
    server_name {DOMAIN};

    ssl_certificate     {CERT_DIR}/fullchain.pem;
    ssl_certificate_key {CERT_DIR}/privkey.pem;
    ssl_protocols TLSv1.2 TLSv1.3;
    ssl_prefer_server_ciphers off;
    ssl_session_cache shared:tauapi_tls:10m;
    ssl_session_timeout 1d;

    # Query strings may carry OAuth codes or reset tokens: log the path only.
    access_log /var/log/nginx/tauapi.access.log tauapi_safe;
    error_log  /var/log/nginx/tauapi.error.log warn;

    client_max_body_size 100m;
    server_tokens off;
    include /etc/nginx/tauapi/security-headers.conf;

    error_page 503 /__maintenance.html;
    location = /__maintenance.html {{
        internal;
        root /srv/tauapi/maintenance;
        try_files /index.html =404;
        add_header Cache-Control "no-store" always;
        include /etc/nginx/tauapi/security-headers.conf;
    }}
{gate}
    location ^~ /.well-known/acme-challenge/ {{
        root /var/www/tauapi-acme;
        default_type text/plain;
        try_files $uri =404;
    }}

    # Hidden files and repository/backup artefacts are never served.
    location ~ /\\.(?!well-known/) {{ return 404; }}

    # ---- Backend exceptions that must win over SPA page prefixes ----
    location ^~ /dashboard/billing/ {{
        include /etc/nginx/tauapi/proxy-backend.conf;
    }}
    location ~ ^/[^/]+/mj/ {{
        include /etc/nginx/tauapi/proxy-backend.conf;
    }}

    # ---- Immutable versioned frontend assets ----
    location ^~ /_ui/ {{
        root /srv/tauapi/public;
        try_files $uri =404;
        # No `always`: only successful responses are cacheable; a missing
        # asset 404 must never be cached as immutable.
        add_header Cache-Control "public, max-age=31536000, immutable";
        include /etc/nginx/tauapi/security-headers.conf;
    }}

    # ---- Frontend version metadata ----
    location = /_meta/ui-version.json {{
        alias /srv/tauapi/current/frontend/ui-version.json;
        default_type application/json;
        add_header Cache-Control "no-cache, no-store, must-revalidate" always;
        include /etc/nginx/tauapi/security-headers.conf;
    }}
    location ^~ /_meta/ {{ return 404; }}

    # ---- Unversioned root public files (revalidate) ----
    location ~ {root_files_re} {{
        root /srv/tauapi/current/frontend;
        try_files $uri =404;
        add_header Cache-Control "no-cache" always;
        include /etc/nginx/tauapi/security-headers.conf;
    }}

    # ---- SPA entry: registered pages only ----
    location = / {{
        root /srv/tauapi/current/frontend;
        try_files /index.html =404;
        add_header Cache-Control "no-cache, no-store, must-revalidate" always;
        include /etc/nginx/tauapi/security-headers.conf;
    }}
    location ~ {page_re} {{
        root /srv/tauapi/current/frontend;
        try_files /index.html =404;
        add_header Cache-Control "no-cache, no-store, must-revalidate" always;
        include /etc/nginx/tauapi/security-headers.conf;
    }}

    # ---- Everything else: API-only backend (API, relay, plugins, JSON 404) ----
    location / {{
        include /etc/nginx/tauapi/proxy-backend.conf;
    }}
}}
"""


SECURITY_HEADERS = """# Shared security headers (generated). Included at server level and in every
# location that sets its own add_header (Nginx does not inherit them there).
add_header X-Content-Type-Options nosniff always;
add_header Referrer-Policy strict-origin-when-cross-origin always;
add_header Strict-Transport-Security "max-age=31536000" always;
"""

PROXY_INCLUDE = """# Shared backend proxy semantics (generated).
proxy_pass http://tauapi_backend;
proxy_http_version 1.1;
proxy_set_header Host $host;
proxy_set_header X-Real-IP $remote_addr;
proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
proxy_set_header X-Forwarded-Proto $scheme;
proxy_set_header Upgrade $http_upgrade;
proxy_set_header Connection $connection_upgrade;
proxy_buffering off;
proxy_cache off;
proxy_read_timeout 600s;
proxy_send_timeout 600s;
proxy_intercept_errors off;
proxy_next_upstream error timeout;
proxy_next_upstream_tries 2;
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--contract", required=True)
    ap.add_argument("--mode", choices=["maintenance", "live"], required=True)
    ap.add_argument("--out", default="-")
    ap.add_argument("--proxy-include-out")
    ap.add_argument("--check-plugins")
    a = ap.parse_args()
    contract = json.load(open(a.contract))
    if a.check_plugins:
        conflicts = check_plugin_conflicts(contract, a.check_plugins)
        if conflicts:
            for c in conflicts:
                print("route conflict: %s %s (%s)" % c, file=sys.stderr)
            return 5
    text = render(contract, a.mode)
    if a.out == "-":
        sys.stdout.write(text)
    else:
        with open(a.out, "w") as fh:
            fh.write(text)
    if a.proxy_include_out:
        with open(a.proxy_include_out, "w") as fh:
            fh.write(PROXY_INCLUDE)
        sec = os.path.join(os.path.dirname(a.proxy_include_out), "security-headers.conf")
        with open(sec, "w") as fh:
            fh.write(SECURITY_HEADERS)
    return 0


if __name__ == "__main__":
    sys.exit(main())
